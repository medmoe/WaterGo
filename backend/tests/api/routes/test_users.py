def test_delete_user_me(client: TestClient, db: Session) -> None:
    user = create_random_user(db)
    user_id = user.id
    headers = get_auth_headers_for_user(user)
    r = client.delete(f"{settings.API_V1_STR}/users/me", headers=headers)
